// Gallery API backed by R2. Viewing is public; uploading and deleting
// require the GALLERY_PASSWORD secret as a Bearer token.

const KEY_PREFIX = 'img/';
const MAX_FILE_BYTES = 10 * 1024 * 1024;
const MAX_FILES_PER_UPLOAD = 20;
const DAILY_COUNT = 5;
// "Today" for the daily picks follows Korea Standard Time (UTC+9).
const DAY_OFFSET_MS = 9 * 60 * 60 * 1000;

export interface GalleryEnv {
    GALLERY: R2Bucket;
    GALLERY_PASSWORD: string;
}

interface GalleryImage {
    id: string;
    uploaded: string;
}

const IMAGE_TYPES: {
    type: string;
    ext: string;
    magic: (b: Uint8Array) => boolean;
}[] = [
    {
        type: 'image/jpeg',
        ext: 'jpg',
        magic: (b) => b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff,
    },
    {
        type: 'image/png',
        ext: 'png',
        magic: (b) =>
            b[0] === 0x89 && b[1] === 0x50 && b[2] === 0x4e && b[3] === 0x47,
    },
    {
        type: 'image/gif',
        ext: 'gif',
        magic: (b) =>
            b[0] === 0x47 && b[1] === 0x49 && b[2] === 0x46 && b[3] === 0x38,
    },
    {
        type: 'image/webp',
        ext: 'webp',
        magic: (b) =>
            b[0] === 0x52 &&
            b[1] === 0x49 &&
            b[2] === 0x46 &&
            b[3] === 0x46 &&
            b[8] === 0x57 &&
            b[9] === 0x45 &&
            b[10] === 0x42 &&
            b[11] === 0x50,
    },
];

// Ids are generated by the server; anything else is rejected before it
// reaches R2 so a path cannot escape the img/ prefix.
const ID_PATTERN = /^[a-z0-9]+-[0-9a-f-]{36}\.(jpg|png|gif|webp)$/;

function json(
    body: unknown,
    status = 200,
    headers: HeadersInit = {},
): Response {
    return Response.json(body, { status, headers });
}

async function sha256(text: string): Promise<ArrayBuffer> {
    return crypto.subtle.digest('SHA-256', new TextEncoder().encode(text));
}

async function isAuthorized(
    request: Request,
    env: GalleryEnv,
): Promise<boolean> {
    const header = request.headers.get('Authorization') ?? '';
    const match = header.match(/^Bearer (.+)$/);
    if (!match || !env.GALLERY_PASSWORD) return false;
    // The client URI-encodes the password so non-ASCII passwords survive
    // the Latin-1-only header.
    let password: string;
    try {
        password = decodeURIComponent(match[1]);
    } catch {
        return false;
    }
    // Hash both sides so the comparison is constant-time and length-independent.
    const [given, expected] = await Promise.all([
        sha256(password),
        sha256(env.GALLERY_PASSWORD),
    ]);
    return crypto.subtle.timingSafeEqual(given, expected);
}

async function listImages(env: GalleryEnv): Promise<GalleryImage[]> {
    const images: GalleryImage[] = [];
    let cursor: string | undefined;
    do {
        const page = await env.GALLERY.list({ prefix: KEY_PREFIX, cursor });
        for (const obj of page.objects) {
            images.push({
                id: obj.key.slice(KEY_PREFIX.length),
                uploaded: obj.uploaded.toISOString(),
            });
        }
        cursor = page.truncated ? page.cursor : undefined;
    } while (cursor);
    return images;
}

function todayKey(now = Date.now()): string {
    return new Date(now + DAY_OFFSET_MS).toISOString().slice(0, 10);
}

// FNV-1a string hash -> mulberry32 PRNG: the same date always yields the same picks.
function seededRandom(seed: string): () => number {
    let h = 0x811c9dc5;
    for (let i = 0; i < seed.length; i++) {
        h ^= seed.charCodeAt(i);
        h = Math.imul(h, 0x01000193);
    }
    let a = h >>> 0;
    return () => {
        a = (a + 0x6d2b79f5) >>> 0;
        let t = a;
        t = Math.imul(t ^ (t >>> 15), t | 1);
        t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
        return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
}

export function pickDaily<T>(
    items: T[],
    day: string,
    count = DAILY_COUNT,
): T[] {
    const pool = [...items];
    const random = seededRandom(day);
    const n = Math.min(count, pool.length);
    // Partial Fisher-Yates shuffle.
    for (let i = 0; i < n; i++) {
        const j = i + Math.floor(random() * (pool.length - i));
        [pool[i], pool[j]] = [pool[j], pool[i]];
    }
    return pool.slice(0, n);
}

async function handleUpload(
    request: Request,
    env: GalleryEnv,
): Promise<Response> {
    let form: FormData;
    try {
        form = await request.formData();
    } catch {
        return json(
            { success: false, error: 'expected multipart form data' },
            400,
        );
    }

    const files = form
        .getAll('files')
        .filter((f): f is File => typeof f !== 'string');
    if (files.length === 0) {
        return json({ success: false, error: 'no files' }, 400);
    }
    if (files.length > MAX_FILES_PER_UPLOAD) {
        return json(
            {
                success: false,
                error: `at most ${MAX_FILES_PER_UPLOAD} files per upload`,
            },
            400,
        );
    }

    // Validate everything before writing anything.
    const prepared: {
        key: string;
        body: ArrayBuffer;
        type: string;
        id: string;
    }[] = [];
    for (const file of files) {
        if (file.size > MAX_FILE_BYTES) {
            return json(
                { success: false, error: `${file.name}: larger than 10MB` },
                413,
            );
        }
        const body = await file.arrayBuffer();
        const head = new Uint8Array(body.slice(0, 12));
        const kind = IMAGE_TYPES.find((t) => t.magic(head));
        if (!kind) {
            return json(
                {
                    success: false,
                    error: `${file.name}: only JPEG, PNG, GIF and WebP are allowed`,
                },
                415,
            );
        }
        const id = `${Date.now().toString(36)}-${crypto.randomUUID()}.${kind.ext}`;
        prepared.push({ key: KEY_PREFIX + id, body, type: kind.type, id });
    }

    const uploaded: GalleryImage[] = [];
    for (const item of prepared) {
        const obj = await env.GALLERY.put(item.key, item.body, {
            httpMetadata: { contentType: item.type },
        });
        uploaded.push({ id: item.id, uploaded: obj.uploaded.toISOString() });
    }
    return json({ success: true, images: uploaded }, 201);
}

async function serveImage(
    id: string,
    request: Request,
    env: GalleryEnv,
): Promise<Response> {
    const obj = await env.GALLERY.get(KEY_PREFIX + id, {
        onlyIf: request.headers,
    });
    if (!obj) return json({ success: false, error: 'not found' }, 404);

    const headers = new Headers();
    obj.writeHttpMetadata(headers);
    headers.set('ETag', obj.httpEtag);
    // Ids are unique per upload, so the bytes behind a URL never change.
    headers.set('Cache-Control', 'public, max-age=31536000, immutable');
    headers.set('X-Content-Type-Options', 'nosniff');

    if (!('body' in obj)) {
        return new Response(null, { status: 304, headers });
    }
    return new Response(obj.body, { headers });
}

/** Handles /gallery/* (path already stripped of the /api prefix). */
export async function handleGallery(
    path: string,
    request: Request,
    env: GalleryEnv,
): Promise<Response | null> {
    const method = request.method;

    if (path === '/gallery' && method === 'GET') {
        const images = await listImages(env);
        images.sort((a, b) => b.uploaded.localeCompare(a.uploaded));
        return json({ success: true, images }, 200, {
            'Cache-Control': 'no-store',
        });
    }

    if (path === '/gallery/daily' && method === 'GET') {
        const day = todayKey();
        const images = await listImages(env);
        images.sort((a, b) => a.id.localeCompare(b.id));
        return json(
            { success: true, day, images: pickDaily(images, day) },
            200,
            {
                'Cache-Control': 'public, max-age=60',
            },
        );
    }

    if (path === '/gallery/auth' && method === 'POST') {
        return (await isAuthorized(request, env))
            ? json({ success: true })
            : json({ success: false, error: 'unauthorized' }, 401);
    }

    if (path === '/gallery/images' && method === 'POST') {
        if (!(await isAuthorized(request, env))) {
            return json({ success: false, error: 'unauthorized' }, 401);
        }
        return handleUpload(request, env);
    }

    const imageMatch = path.match(/^\/gallery\/images\/([^/]+)$/);
    if (imageMatch) {
        const id = decodeURIComponent(imageMatch[1]);
        if (!ID_PATTERN.test(id)) {
            return json({ success: false, error: 'not found' }, 404);
        }
        if (method === 'GET' || method === 'HEAD') {
            return serveImage(id, request, env);
        }
        if (method === 'DELETE') {
            if (!(await isAuthorized(request, env))) {
                return json({ success: false, error: 'unauthorized' }, 401);
            }
            await env.GALLERY.delete(KEY_PREFIX + id);
            return json({ success: true });
        }
    }

    return null;
}
